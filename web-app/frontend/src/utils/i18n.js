export function getLanguage(language) {
  return supportedLanguages.includes(language) ? language : "en";
}

export function t(language, key) {
  const safeLanguage = getLanguage(language);
  return texts[safeLanguage][key] ?? texts.en[key] ?? key;
}

export function textBundle(language) {
  return texts[getLanguage(language)];
}

export function labelFor(language, category, rawValue) {
  const safeLanguage = getLanguage(language);
  return valueLabels[safeLanguage]?.[category]?.[rawValue] ?? rawValue;
}

export function optionSearchText(language, category, rawValue) {
  return `${rawValue} ${labelFor(language, category, rawValue)}`.toLowerCase();
}
